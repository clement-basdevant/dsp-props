"""Copy the functions under mutation from the installed SciPy into ``target/scipy_subset.py``.

Usage: python benchmarks/automutation/extract.py   (with SciPy 1.18.1 installed)

The copy is verbatim (SciPy is BSD-licensed; the notice is kept in the file header). The module
starts from the namespace of ``scipy.signal._signaltools`` so that the private helpers the
functions use resolve as in SciPy, then redefines the functions below, so that a call from one
copied function to another (``decimate`` calls ``resample_poly``) reaches the mutated copy.
"""

from __future__ import annotations

import ast
import inspect
import pathlib

import scipy
import scipy.signal._signaltools as st

FUNCTIONS = ["resample", "resample_poly", "decimate", "hilbert"]
VERSION = "1.18.1"
HERE = pathlib.Path(__file__).resolve().parent

HEADER = f'''"""Copies of scipy.signal functions (SciPy {VERSION}, scipy/signal/_signaltools.py), the target of
the automatic mutation campaign (plan 3.2). Generated by benchmarks/automutation/extract.py; do not
edit by hand.

Copyright (c) 2001-2002 Enthought, Inc. 2003, SciPy Developers. All rights reserved.
Redistributed under the BSD 3-Clause license of SciPy (https://github.com/scipy/scipy/blob/main/LICENSE.txt).
"""
# ruff: noqa
# fmt: off
import scipy.signal._signaltools as _st

globals().update({{k: v for k, v in vars(_st).items() if not k.startswith("__")}})

'''


def main():
    if scipy.__version__ != VERSION:
        raise SystemExit(f"SciPy {VERSION} is needed, found {scipy.__version__}")
    source = inspect.getsource(st)
    tree = ast.parse(source)
    lines = source.splitlines()
    nodes = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    parts = []
    for name in FUNCTIONS:
        node = nodes[name]
        start = min([node.lineno] + [d.lineno for d in node.decorator_list])
        parts.append("\n".join(lines[start - 1:node.end_lineno]))
    out = HEADER + "\n\n\n".join(parts) + "\n"
    (HERE / "target" / "scipy_subset.py").write_text(out)
    print(f"{len(FUNCTIONS)} functions, {out.count(chr(10))} lines -> target/scipy_subset.py")


if __name__ == "__main__":
    main()
