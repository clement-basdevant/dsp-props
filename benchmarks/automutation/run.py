"""Automatic mutation of scipy.signal code: SciPy's own tests against dsp-props (plan 3.2).

Usage (in an environment with SciPy 1.18.1, cosmic-ray 8.9, pytest and dsp-props):
    python benchmarks/automutation/run.py [--workers 4] [--limit N] [--json results.json]

The mutants are generated by cosmic-ray (``cosmic-ray init`` then ``cr-filter-operators`` with
``cosmic-ray.toml``) on ``target/scipy_subset.py``, a verbatim copy of four functions of
SciPy 1.18.1 (``extract.py``). Each mutant is applied with ``cosmic-ray apply`` in a private copy of
the target and checked by three test runs:

* ``upstream``: SciPy's own tests of these functions (``TestResample``, ``TestDecimate``,
  ``TestHilbert`` of ``scipy/signal/tests/test_signaltools.py``, 254 tests), patched to call the copy;
* ``dsp_fast``: the dsp-props declarations of ``dsp_tests/`` with the fast profile (30 inputs per
  relation), derandomized;
* ``dsp_default``: the same with the default profile (200 inputs), only for the mutants that
  ``dsp_fast`` did not kill.

A run that fails (pytest exit code 1) or cannot import the mutated module (exit code 2) kills the
mutant; a run longer than its timeout counts as killed too (``timeout``), as in cosmic-ray.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import difflib
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import time

HERE = pathlib.Path(__file__).resolve().parent
TARGET = HERE / "target"
SESSION = "session.sqlite"

PYTEST = [sys.executable, "-m", "pytest", "-x", "-q", "-p", "no:cacheprovider", "-p", "scipy_patch"]
SUITES = {
    "upstream": (PYTEST + ["--pyargs", "scipy.signal.tests.test_signaltools",
                           "-k", "TestResample or TestDecimate or TestHilbert"], 120),
    "dsp_fast": (PYTEST + [str(HERE / "dsp_tests"), "--dsp-props-profile", "fast",
                           "--dsp-props-derandomize", "--dsp-props-database", "none"], 120),
    "dsp_default": (PYTEST + [str(HERE / "dsp_tests"), "--dsp-props-profile", "default",
                              "--dsp-props-derandomize", "--dsp-props-database", "none"], 400),
}


def cosmic(*args, cwd=HERE):
    exe = pathlib.Path(sys.executable).with_name("cosmic-ray")
    return subprocess.run([str(exe), *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def mutants(session: pathlib.Path):
    """The work items cosmic-ray kept after filtering (one mutation each)."""
    out = []
    for line in cosmic("dump", str(session)).splitlines():
        item, result = json.loads(line)
        if result and result.get("worker_outcome") == "skipped":
            continue
        (m,) = item["mutations"]
        out.append({"id": item["job_id"], "operator": m["operator_name"], "occurrence": m["occurrence"],
                    "function": m.get("definition_name"), "line": m["start_pos"][0]})
    return out


def run_suite(name, cwd):
    cmd, timeout = SUITES[name]
    env = {**os.environ, "PYTHONPATH": str(cwd / "target")}
    t0 = time.perf_counter()
    try:
        proc = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True, timeout=timeout)
        code = proc.returncode
        outcome = "survived" if code == 0 else "killed" if code in (1, 2) else f"error {code}"
    except subprocess.TimeoutExpired:
        outcome = "timeout"
    return outcome, round(time.perf_counter() - t0, 1)


def check(mutant, workdir: pathlib.Path):
    shutil.copy(TARGET / "scipy_subset.py", workdir / "target" / "scipy_subset.py")
    pristine = (workdir / "target" / "scipy_subset.py").read_text().splitlines()
    pathlib.Path(workdir / "target" / "scipy_subset.py")
    exe = pathlib.Path(sys.executable).with_name("cosmic-ray")
    subprocess.run([str(exe), "apply", "target/scipy_subset.py", mutant["operator"], str(mutant["occurrence"])],
                   cwd=workdir, check=True, capture_output=True)
    mutated = (workdir / "target" / "scipy_subset.py").read_text().splitlines()
    diff = [d for d in difflib.unified_diff(pristine, mutated, lineterm="", n=0)][2:]
    row = {**mutant, "diff": diff}
    for suite in ("upstream", "dsp_fast"):
        row[suite], row[suite + "_seconds"] = run_suite(suite, workdir)
    if row["dsp_fast"] == "survived":
        row["dsp_default"], row["dsp_default_seconds"] = run_suite("dsp_default", workdir)
    else:
        row["dsp_default"] = row["dsp_fast"]  # a mutant killed with 30 inputs is killed with 200
    return row


def killed(outcome):
    return outcome in ("killed", "timeout")


def summary(rows):
    by = {}
    for r in rows:
        for key in (r["function"], "all"):
            s = by.setdefault(key, {"mutants": 0, "upstream": 0, "dsp_fast": 0, "dsp_default": 0,
                                    "both": 0, "upstream_only": 0, "dsp_only": 0, "neither": 0})
            s["mutants"] += 1
            up, dsp = killed(r["upstream"]), killed(r["dsp_default"])
            s["upstream"] += up
            s["dsp_fast"] += killed(r["dsp_fast"])
            s["dsp_default"] += dsp
            s["both" if up and dsp else "upstream_only" if up else "dsp_only" if dsp else "neither"] += 1
    return by


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--limit", type=int, help="first N mutants only (a quick check)")
    parser.add_argument("--json", type=pathlib.Path, default=HERE / "results.json")
    parser.add_argument("--checkpoint", type=pathlib.Path, default=HERE / "partial.jsonl",
                        help="one line per checked mutant; a rerun skips those already there")
    args = parser.parse_args()
    done_rows = {}
    if args.checkpoint.exists():
        for line in args.checkpoint.read_text().splitlines():
            r = json.loads(line)
            done_rows[(r["operator"], r["occurrence"])] = r

    with tempfile.TemporaryDirectory() as tmp:
        session = pathlib.Path(tmp) / SESSION
        cosmic("init", "cosmic-ray.toml", str(session))
        exe = pathlib.Path(sys.executable).with_name("cr-filter-operators")
        subprocess.run([str(exe), str(session), "cosmic-ray.toml"], cwd=HERE, check=True,
                       capture_output=True)
        todo = mutants(session)[: args.limit]
        rows = [done_rows[k] for k in ((m["operator"], m["occurrence"]) for m in todo) if k in done_rows]
        todo = [m for m in todo if (m["operator"], m["occurrence"]) not in done_rows]
        workdirs = []
        for i in range(args.workers):
            w = pathlib.Path(tmp) / f"w{i}"
            shutil.copytree(TARGET, w / "target")
            workdirs.append(w)
        free = list(workdirs)
        print(f"{len(todo)} mutants to check ({len(rows)} from the checkpoint), {args.workers} workers", flush=True)
        with concurrent.futures.ThreadPoolExecutor(args.workers) as pool:
            futures = {}
            pending = list(todo)
            while pending or futures:
                while pending and free:
                    w = free.pop()
                    futures[pool.submit(check, pending.pop(0), w)] = w
                done, _ = concurrent.futures.wait(futures, return_when=concurrent.futures.FIRST_COMPLETED)
                for f in done:
                    free.append(futures.pop(f))
                    rows.append(f.result())
                    with args.checkpoint.open("a") as fh:
                        fh.write(json.dumps(rows[-1]) + "\n")
                    if len(rows) % 25 == 0:
                        print(f"  {len(rows)} checked", flush=True)
    rows.sort(key=lambda r: (r["function"] or "", r["line"], r["operator"], r["occurrence"]))
    result = {"scipy": "1.18.1", "tool": "cosmic-ray 8.9.0", "suites": {k: " ".join(v[0][1:]) for k, v in SUITES.items()},
              "summary": summary(rows), "mutants": rows}
    args.json.write_text(json.dumps(result, indent=1) + "\n")
    for key, s in result["summary"].items():
        print(f"{str(key):<14} {s}")


if __name__ == "__main__":
    main()
