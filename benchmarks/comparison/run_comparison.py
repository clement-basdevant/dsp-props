"""Compare dsp-props with the state of practice on automatically mutated subjects.

For each subject in ``subjects/`` (FFT, lfilter, upfirdn, overlap-add):

1. every first-order mutant is generated by ``mutate.py``;
2. the oracle of ``suites.py`` classifies it against an independent reference:
   *equivalent* if the largest relative error is at most 1e-12, *accuracy*
   fault if it lies in (1e-12, 1e-6], *functional* fault above 1e-6 or when
   the mutant raises, returns the wrong shape or hangs;
3. every approach of ``approaches.py`` is run against it: the state-of-practice
   suite once (it is deterministic), the randomised approaches once per seed.

Each job runs in a worker process with a time limit; a job that exceeds it
counts as a kill (a test suite that hangs fails in CI) and is recorded as such.
Results are appended to a JSON-lines file so that an interrupted run resumes,
and summarised by ``--summary``.

    python benchmarks/comparison/run_comparison.py                 # all subjects, 5 seeds
    python benchmarks/comparison/run_comparison.py --subjects fft --seeds 1
    python benchmarks/comparison/run_comparison.py --summary
"""

from __future__ import annotations

import argparse
import json
import multiprocessing as mp
import os
import resource
import signal
import sys
import time
import types
import warnings
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path[:0] = [str(HERE), str(ROOT / "src")]

import numpy as np  # noqa: E402

import approaches  # noqa: E402
import mutate  # noqa: E402
import suites  # noqa: E402

DEFAULT_OUT = HERE / "results.jsonl"
SUBJECT_NAMES = ["fft", "lfilter", "upfirdn", "ola"]
EQUIVALENT, ACCURACY = 1e-12, 1e-6


class Timeout(BaseException):
    """Not an Exception, so that Hypothesis does not catch it and start shrinking a hanging input."""


def _alarm(signum, frame):
    raise Timeout()


def load(subject: str, mutant_id: str | None, source: str | None = None):
    """Import the subject (or one of its mutants) as a fresh module."""
    path = HERE / "subjects" / f"{subject}.py"
    if source is None:
        source = path.read_text(encoding="utf-8")
    mod = types.ModuleType(f"subject_{subject}_{mutant_id or 'orig'}")
    mod.__file__ = str(path)
    exec(compile(source, str(path), "exec"), mod.__dict__)
    return mod


def relative_error(y, ref):
    y = np.asarray(y)
    ref = np.asarray(ref)
    if y.shape != ref.shape:
        return float("inf")
    if ref.size == 0:
        return 0.0
    if not np.all(np.isfinite(y)):
        return float("inf")
    ref = ref.astype(np.clongdouble if np.iscomplexobj(ref) else np.longdouble)
    num = float(np.linalg.norm((y - ref).astype(complex)))
    den = float(np.linalg.norm(ref.astype(complex)))
    return num / den if den > 0 else num


def classify(subject, mod):
    _, _, oracle = suites.SUBJECTS[subject]
    outs = oracle(mod)
    return max(relative_error(y, ref) for _, _, y, ref in outs)


def _job(args):
    """Run one (subject, mutant, approach, seed) job in a worker; never raises."""
    subject, mid, source, approach, seed, timeout = args
    signal.signal(signal.SIGALRM, _alarm)
    t0 = time.perf_counter()
    record = {"subject": subject, "mutant": mid, "approach": approach, "seed": seed, "time_limit": timeout}
    try:
        # re-fires every 10 s after the first expiry, in case some layer swallows the exception
        signal.setitimer(signal.ITIMER_REAL, timeout, 10)
        with warnings.catch_warnings(), np.errstate(all="ignore"):
            warnings.simplefilter("ignore")
            mod = load(subject, mid, source)
            if approach == "oracle":
                try:
                    err = classify(subject, mod)
                    record.update(error=err, crashed=False)
                except Timeout:
                    raise
                except Exception as exc:  # noqa: BLE001 - a crash is a functional fault
                    record.update(error=float("inf"), crashed=True, exception=type(exc).__name__)
            else:
                decls_f, sop_f, _ = suites.SUBJECTS[subject]
                decls = decls_f(mod) if approach != "sop" else {}
                sop_tests = sop_f(mod) if approach == "sop" else []
                record.update(approaches.run_approach(approach, decls, sop_tests, seed))
        signal.setitimer(signal.ITIMER_REAL, 0)
        # a time-out inside a test is caught by the approach as a failure: flag it as a time-out
        record["timeout"] = any(f.get("error") == "Timeout" for f in record.get("failures", []))
    except Timeout:
        record.update(killed=True, timeout=True, error=float("inf") if approach == "oracle" else None)
    except MemoryError:
        signal.setitimer(signal.ITIMER_REAL, 0)
        record.update(killed=True, timeout=False, memory=True,
                      error=float("inf") if approach == "oracle" else None)
    except BaseException as exc:  # noqa: BLE001
        signal.setitimer(signal.ITIMER_REAL, 0)
        record.update(killed=True, timeout=False, harness_error=f"{type(exc).__name__}: {exc}"[:300])
    record["wall"] = round(time.perf_counter() - t0, 3)
    return record


def _init_worker(mem_gb):
    limit = int(mem_gb * 2**30)
    resource.setrlimit(resource.RLIMIT_AS, (limit, limit))
    os.environ.setdefault("OMP_NUM_THREADS", "1")


def _done(out: Path):
    done = set()
    if out.exists():
        for line in out.read_text().splitlines():
            r = json.loads(line)
            done.add((r["subject"], r["mutant"], r["approach"], r["seed"]))
    return done


def build_jobs(subjects, seeds, approach_names, timeout, oracle_timeout):
    jobs = []
    for subject in subjects:
        path = HERE / "subjects" / f"{subject}.py"
        originals = [(None, None)]
        ms = [(m.id, m.source) for m in mutate.mutants(str(path))]
        for mid, source in originals + ms:
            mid = mid or f"{subject}-orig"
            jobs.append((subject, mid, source, "oracle", 0, oracle_timeout))
            for approach in approach_names:
                for seed in (range(seeds) if approach in approaches.RANDOMISED else [0]):
                    jobs.append((subject, mid, source, approach, seed, timeout))
    return jobs


def run(args):
    out = Path(args.out)
    done = _done(out)
    approach_names = args.approaches or approaches.APPROACHES
    jobs = [j for j in build_jobs(args.subjects, args.seeds, approach_names, args.timeout, args.oracle_timeout)
            if (j[0], j[1], j[3], j[4]) not in done]
    # oracle jobs first, then the longest (randomised) ones, to keep the pool busy
    jobs.sort(key=lambda j: (j[3] != "oracle", j[3] == "sop"))
    print(f"{len(done)} jobs already done, {len(jobs)} to run on {args.workers} workers", flush=True)
    t0 = time.time()
    # No maxtasksperchild: a replacement worker is forked from the pool's helper thread, and
    # Python then never runs its SIGALRM handler, so the time limit would silently stop working.
    with mp.get_context("fork").Pool(args.workers, initializer=_init_worker, initargs=(args.mem_gb,)) as pool, \
            out.open("a") as fh:
        for k, record in enumerate(pool.imap_unordered(_job, jobs, chunksize=1), 1):
            fh.write(json.dumps(record) + "\n")
            fh.flush()
            if k % 50 == 0 or k == len(jobs):
                print(f"  {k}/{len(jobs)} jobs, {time.time() - t0:.0f} s", flush=True)


# ----------------------------------------------------------------------------- summary

def category(err, crashed=False):
    if crashed or err is None or not np.isfinite(err) or err > ACCURACY:
        return "functional"
    if err > EQUIVALENT:
        return "accuracy"
    return "equivalent"


def summarise(path: Path):
    records = [json.loads(line) for line in path.read_text().splitlines()]
    cls = {}
    runs = defaultdict(list)
    for r in records:
        key = (r["subject"], r["mutant"])
        if r["approach"] == "oracle":
            cls[key] = category(r.get("error"), r.get("crashed", False))
        else:
            runs[(key, r["approach"])].append(r)
    subjects = sorted({k[0] for k in cls}, key=SUBJECT_NAMES.index)
    approach_names = [a for a in approaches.APPROACHES if any(a == k[1] for k in runs)]
    summary = {"classification": {}, "kill_rates": {}, "originals": {}, "per_mutant": {},
               "first_failure": {}, "counterexample_length": {}, "seconds": {}, "timeouts": {}}
    for subject in subjects + ["all"]:
        keys = [k for k in cls if (subject == "all" or k[0] == subject) and not k[1].endswith("-orig")]
        counts = defaultdict(int)
        for k in keys:
            counts[cls[k]] += 1
        summary["classification"][subject] = dict(counts, total=len(keys))
        for cat in ("functional", "accuracy"):
            group = [k for k in keys if cls[k] == cat]
            for a in approach_names:
                per_seed = defaultdict(list)
                for k in group:
                    for r in runs.get((k, a), []):
                        per_seed[r["seed"]].append(bool(r.get("killed")))
                rates = [sum(v) / len(v) for v in per_seed.values() if v]
                if rates:
                    summary["kill_rates"].setdefault(subject, {}).setdefault(cat, {})[a] = {
                        "mean": float(np.mean(rates)), "min": float(np.min(rates)), "max": float(np.max(rates)),
                        "n_mutants": len(group), "n_seeds": len(rates)}
        # false alarms on equivalent mutants and on the original
        eq = [k for k in keys if cls[k] == "equivalent"]
        for a in approach_names:
            fa = [bool(r.get("killed")) for k in eq for r in runs.get((k, a), [])]
            if fa:
                summary["kill_rates"].setdefault(subject, {}).setdefault("equivalent", {})[a] = {
                    "mean": float(np.mean(fa)), "n_mutants": len(eq)}
    for (key, a), rs in runs.items():
        if key[1].endswith("-orig"):
            summary["originals"].setdefault(key[0], {})[a] = sum(bool(r.get("killed")) for r in rs)
    for a in approach_names:
        ff = [f["first_failure"] for (key, ap), rs in runs.items() if ap == a and cls.get(key) == "functional"
              for r in rs for f in r.get("failures", [])[:1] if f.get("first_failure")]
        cl = [f["counterexample_length"] for (key, ap), rs in runs.items() if ap == a
              and cls.get(key) == "functional" for r in rs for f in r.get("failures", [])[:1]
              if f.get("counterexample_length") is not None]
        secs = [r.get("seconds", r["wall"]) for (key, ap), rs in runs.items() if ap == a for r in rs]
        if ff:
            summary["first_failure"][a] = {"median": float(np.median(ff)), "p90": float(np.percentile(ff, 90))}
        if cl:
            summary["counterexample_length"][a] = {"median": float(np.median(cl)), "p90": float(np.percentile(cl, 90)),
                                                   "max": int(np.max(cl))}
        if secs:
            summary["seconds"][a] = {"median": float(np.median(secs)), "total": float(np.sum(secs))}
        summary["timeouts"][a] = sum(bool(r.get("timeout")) for (key, ap), rs in runs.items() if ap == a for r in rs)
    # which mutants each approach misses (majority over seeds), for the discussion
    for key, c in cls.items():
        if key[1].endswith("-orig") or c == "equivalent":
            continue
        summary["per_mutant"][key[1]] = {
            "class": c, **{a: float(np.mean([bool(r.get("killed")) for r in runs.get((key, a), [])]))
                           for a in approach_names if runs.get((key, a))}}
    return summary


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--subjects", nargs="+", default=SUBJECT_NAMES, choices=SUBJECT_NAMES)
    p.add_argument("--approaches", nargs="+", choices=approaches.APPROACHES)
    p.add_argument("--seeds", type=int, default=5)
    p.add_argument("--timeout", type=int, default=90, help="seconds per approach run (a full run on the correct FFT subject takes about 35 s on an idle core)")
    p.add_argument("--oracle-timeout", type=int, default=120)
    p.add_argument("--workers", type=int, default=os.cpu_count())
    p.add_argument("--mem-gb", type=float, default=3.0, help="address-space limit per worker")
    p.add_argument("--out", default=str(DEFAULT_OUT))
    p.add_argument("--summary", action="store_true", help="summarise --out into JSON and exit")
    args = p.parse_args(argv)
    if args.summary:
        s = summarise(Path(args.out))
        Path(args.out).with_name("summary.json").write_text(json.dumps(s, indent=1))
        print(json.dumps({k: s[k] for k in ("classification", "kill_rates", "originals", "timeouts")}, indent=1))
        return
    run(args)


if __name__ == "__main__":
    main()
